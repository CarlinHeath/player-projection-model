CREATE TABLE players (
    player_id int PRIMARY KEY,
    last_name varchar,
    first_name varchar,
    full_name varchar,
    birth_date date,
    bats char,
    throws char,
    position varchar,
    active boolean,
    debut_date date,
    height_in_inches int,
    weight_in_pounds int
);

CREATE TABLE teams (
    team_id int PRIMARY KEY,
    name varchar,
    league varchar,
    division varchar
);

CREATE TABLE hitting_season_stats (
    stat_id INTEGER PRIMARY KEY,
    age int,
    season varchar,
    games_played int,
    plate_appearances int,
    ground_outs int,
    air_outs int,
    runs int,
    doubles int,
    triples int,
    home_runs int,
    strike_outs int,
    base_on_balls int,
    intentional_walks int,
    hit_by_pitch int,
    hits int,
    at_bats int,
    batting_average float,
    on_base_percentage float,
    slugging float,
    on_base_plus_slugging float,
    stolen_bases int,
    caught_stealing int,
    number_of_pitches int,
    runs_batted_in int,
    batting_average_on_balls_in_play float,
    sacrifice_bunts int,
    sacrifice_flies int,
    catcher_interference int,
    player_id int,
    team_id int,
    FOREIGN KEY (player_id) REFERENCES players(player_id),
    FOREIGN KEY (team_id) REFERENCES teams(team_id)
);

CREATE TABLE pitching_season_stats (
    stat_id INTEGER PRIMARY KEY,
    age int,
    season varchar,
    games_played int,
    games_started int,
    ground_outs int,
    air_outs int,
    runs int,
    home_runs int,
    strike_outs int,
    base_on_balls int,
    intentional_walks int,
    hit_batsmen int,
    hits_allowed int,
    batting_average_against float,
    batters_faced int,
    on_base_percentage float,
    slugging float,
    on_base_plus_slugging float,
    caught_stealing int,
    stolen_bases int,
    ground_into_double_play int,
    number_of_pitches int,
    earned_run_average float,
    outs int,
    wins int,
    losses int,
    saves int,
    save_opportunities int,
    blown_saves int,
    holds int,
    earned_runs int,
    walks_plus_hits_per_inning_pitched float,
    complete_games int,
    shutouts int,
    strike_percentage float,
    pitches_per_inning float,
    strike_outs_per_9 float,
    base_on_balls_per_9 float,
    hits_per_9 float,
    home_runs_per_9 float,
    inherited_runners int,
    inherited_runners_scored int,
    player_id int,
    team_id int,
    FOREIGN KEY (player_id) REFERENCES players(player_id),
    FOREIGN KEY (team_id) REFERENCES teams(team_id)
);